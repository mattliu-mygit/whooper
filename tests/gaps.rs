/// page/node_modules when npm ci in page/ installed Vitest and its V8 coverage there, or None, with a
/// note, so the test is skipped.
fn page_vitest() -> Option<PathBuf> {
    let modules = Path::new(env!("CARGO_MANIFEST_DIR")).join("page/node_modules");
    let ok = modules.join(".bin/vitest").exists()
        && modules.join("@vitest/coverage-v8").is_dir()
        && connections_node();
    if !ok {
        eprintln!("skipped: no node or Vitest in page/node_modules; npm ci in page/ installs it");
    }
    ok.then_some(modules)
}

fn connections_node() -> bool {
    std::process::Command::new("node")
        .arg("--version")
        .output()
        .is_ok_and(|o| o.status.success())
}

/// Installs page's Vitest and its V8 coverage in package's node_modules, as the repo's setup script
/// would, in a folder of package's own, so Vitest keeps its cache there.
fn install_vitest(package: &Path, modules: &Path) {
    let own = package.join("node_modules");
    fs::create_dir_all(own.join(".bin")).unwrap();
    for name in ["vitest", "@vitest"] {
        symlink(modules.join(name), own.join(name)).unwrap();
    }
    symlink("../vitest/vitest.mjs", own.join(".bin/vitest")).unwrap();
}

#[test]
fn lists_the_changed_lines_no_vitest_test_ran_in_each_package_whose_tests_run_with_it() {
    let Some(modules) = page_vitest() else { return };
    let w = Whooper::new();
    let run = w.run_dir(WEB, &web_pr());
    install_vitest(&run.join("head/web"), &modules);
    let lines: Vec<Value> = [
        ("web/src/calc.ts", 3),
        ("web/src/routes/[id]/page.ts", 1),
        ("web/src/routes/[id]/page.ts", 2),
        ("web/src/untested.ts", 2),
    ]
    .iter()
    .map(|(p, n)| json!({"path": p, "line": n, "status": "not_run"}))
    .collect();
    assert_eq!(
        gaps(&w, &run, None, &[]).unwrap(),
        json!({
            "measured": true,
            "reason": null,
            "tool": WEB_TOOL,
            "lines": lines,
            "summary": {"changed_lines": 5, "run": 1, "not_run": 4},
            "limits": [NODE_LINES, CHECKED, OWN_TESTS, NO_RUNNER, OTHER_LANGUAGE],
        })
    );
    // Vitest wrote nothing in the worktree but its cache in node_modules.
    let status = w.git(
        &run.join("head"),
        &[
            "status",
            "--porcelain",
            "--ignored",
            "--untracked-files=all",
        ],
    );
    let folders: std::collections::BTreeSet<&str> = status
        .lines()
        .map(|l| l.split("/node_modules/").next().unwrap())
        .collect();
    assert_eq!(folders, ["?? web"].into());
}

#[test]
fn a_jest_package_and_go_merge_into_one_file_with_each_runs_command() {
    let w = Whooper::new();
    // A Go module at the root and a Node package, app, whose tests run with Jest. The fake jest saves
    // its arguments and environment and writes an LCov report that names calc.js by its absolute path,
    // in two records, and exits 1, as Jest does when a test fails. A fake node stands for the one
    // Jest's script needs.
    let calc_head = format!("{}\n", CALC_PR.split("\n\n// Untested").next().unwrap());
    let base = [
        ("go.mod", get(GAPS, "go.mod")),
        ("calc/calc.go", get(GAPS, "calc/calc.go")),
        ("calc/calc_test.go", get(GAPS, "calc/calc_test.go")),
        (
            "app/package.json",
            "{\"name\": \"app\", \"scripts\": {\"test\": \"jest --silent\"}}\n",
        ),
        ("app/src/calc.js", "exports.cap = (n) => n;\n"),
    ];
    let head = over(
        &base,
        &[
            ("calc/calc.go", &calc_head),
            (
                "app/src/calc.js",
                "exports.cap = (n) => {\n  if (n > 9) {\n    return 9;\n  }\n  return n;\n};\n",
            ),
        ],
    );
    let run = w.run_dir(&base, &head);
    let app = fs::canonicalize(&run).unwrap().join("head/app");
    let args = w.root().join("jest-args");
    script(
        &app.join("node_modules/.bin/jest"),
        &[
            format!("printf \"%s\\n\" \"$PWD\" \"$CI $npm_config_offline\" \"$@\" > \"{}\"", args.display()),
            "for arg; do case \"$arg\" in --coverageDirectory=*) out=\"${arg#*=}\" ;; esac; done".into(),
            format!(
                "printf \"TN:\\nSF:{a}/src/calc.js\\nDA:1,1\\nDA:2,1\\nDA:3,0\\nend_of_record\\nSF:{a}/src/calc.js\\nDA:3,0\\nDA:5,2\\nend_of_record\\n\" > \"$out/lcov.info\"",
                a = app.display()
            ),
            "exit 1".into(),
        ]
        .join("\n"),
    );
    w.fake("node", "exit 0");
    let gaps = gaps(&w, &run, None, &[]).unwrap();
    assert_eq!(
        gaps["tool"],
        "GOPROXY=off GOTOOLCHAIN=local go test -count=1 -coverpkg=./calc ./calc; (cd app && CI=true npm_config_offline=true node_modules/.bin/jest --coverage --coverageReporters=lcov --collectCoverageFrom=src/calc.js)"
    );
    // calc.js's cap (3) and calc.go's cap (7) no test ran, in the diff's order.
    assert_eq!(
        pick(&gaps, &["measured", "reason", "lines", "summary"]),
        json!({"measured": true, "reason": null,
               "lines": [{"path": "app/src/calc.js", "line": 3, "status": "not_run"},
                         {"path": "calc/calc.go", "line": 7, "status": "not_run"}],
               "summary": {"changed_lines": 7, "run": 5, "not_run": 2}})
    );
    assert_eq!(
        gaps["limits"],
        json!([
            AND_LINES,
            CHECKED,
            OWN_TESTS,
            NODE_LINES,
            "Jest exited with code 1 in app, as it does when a test fails; the lines the tests ran count as run."
        ])
    );
    let recorded = fs::read_to_string(&args).unwrap();
    let lines: Vec<&str> = recorded.lines().collect();
    assert_eq!(
        (fs::canonicalize(lines[0]).unwrap(), lines[1]),
        (app.clone(), "true true")
    );
    let rest = &lines[2..];
    assert_eq!(
        [&rest[..3], &rest[4..]].concat(),
        [
            "--coverage",
            "--coverageReporters=lcov",
            "--collectCoverageFrom=src/calc.js",
            "--no-watchman"
        ]
    );
    assert!(rest[3].starts_with("--coverageDirectory="), "{}", rest[3]);
}

#[test]
fn nothing_is_measured_without_a_runner_installed_or_a_package() {
    let cases: [(&str, Option<&str>, &str); 4] = [
        (
            "no package.json",
            None,
            "Whooper did not measure 1 changed file, since no package.json is above it: web/src/a.ts.",
        ),
        (
            "no runner",
            Some("{\"scripts\": {\"test\": \"node test.js\"}}"),
            "Whooper did not measure 1 changed file in web, since its package.json names neither Vitest nor Jest: web/src/a.ts.",
        ),
        (
            "not installed",
            Some("{\"devDependencies\": {\"jest\": \"30.0.0\"}}"),
            "Whooper did not measure 1 changed file in web, since its dependencies are not installed: Whooper found no node_modules/.bin/jest there or in a folder above it, which the repo's setup script would install: web/src/a.ts.",
        ),
        (
            "unreadable",
            Some("{"),
            "Whooper did not measure 1 changed file in web, since its package.json cannot be read: ",
        ),
    ];
    for (name, package, why) in cases {
        let w = Whooper::new();
        let mut base = vec![("web/src/a.ts", "export const a = 0;\n")];
        if let Some(p) = package {
            base.push(("web/package.json", p));
        }
        let head = over(&base, &[("web/src/a.ts", "export const a = 1;\n")]);
        let run = w.run_dir(&base, &head);
        let gaps = gaps(&w, &run, None, &[]).unwrap();
        assert_eq!(
            pick(&gaps, &["measured", "tool", "lines", "summary", "limits"]),
            json!({"measured": false, "tool": "", "lines": [],
                   "summary": {"changed_lines": 0, "run": 0, "not_run": 0}, "limits": []}),
            "{name}"
        );
        let reason = gaps["reason"].as_str().unwrap();
        assert!(reason.starts_with(why), "{name}: {reason}");
    }
}

