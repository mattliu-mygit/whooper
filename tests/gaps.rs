#[test]
fn a_failing_test_still_measures_and_says_so() {
    let w = Whooper::new();
    let tests = gaps_tests("\tt.Error(\"fails on purpose\")");
    let run = w.run_dir(GAPS, &over(&gaps_pr(), &[("calc/calc_test.go", &tests)]));
    let gaps = gaps(&w, &run, None, &[]).unwrap();
    assert_eq!(
        pick(&gaps, &["measured", "reason", "lines", "summary"]),
        json!({"measured": true, "reason": null,
               "lines": [{"path": "calc/calc.go", "line": 7, "status": "not_run"}],
               "summary": {"changed_lines": 8, "run": 7, "not_run": 1}})
    );
    assert_eq!(
        gaps["limits"],
        json!([
            AND_LINES,
            CHECKED,
            OWN_TESTS,
            "1 test failed: TestAllowed in example.com/gaps/calc. Go recorded the lines it ran before it failed, so they count as run.",
            LEFT_OUT,
            OTHER_LANGUAGE
        ])
    );
}

