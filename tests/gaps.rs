#[test]
fn gremlins_stops_at_the_steps_time_limit_and_leaves_nothing_running() {
    let w = Whooper::new();
    let run = w.run_dir(MUT, &mut_pr());
    // The test-gaps step would wait for the test too, so the file stands for what it measured.
    fs::write(
        run.join("test_gaps.json"),
        json!({"measured": true, "reason": null, "tool": "go test", "lines": [],
               "summary": {"changed_lines": 4, "run": 4, "not_run": 0}, "limits": []})
        .to_string(),
    )
    .unwrap();
    let pid = w.root().join("gremlins.pid");
    let env = gremlins_env(
        &w,
        Some(&format!("echo $$ > '{}'\nexec sleep 60", pid.display())),
    );
    let started = Instant::now();
    let gaps = mutation(&w, &run, Some(3.0), &env);
    assert!(started.elapsed() < Duration::from_secs(15));
    assert_eq!(
        pick(&gaps, &["lines", "summary"]),
        json!({"lines": [], "summary": {"changed_lines": 4, "run": 4, "not_run": 0, "survived": 0, "caught": 0}})
    );
    assert_eq!(
        gaps["limits"],
        json!([
            "gremlins ran past Whooper's 3-second limit, so Whooper has no survived or caught lines in calc."
        ])
    );
    assert_stopped(&pid);
}

#[test]
fn gremlins_reads_the_lines_the_diff_adds_whatever_the_git_config_says() {
    let w = Whooper::new();
    let run = w.run_dir(MUT, &mut_pr());
    gaps(&w, &run, None, &[]).unwrap();
    // The user's git config changes what git diff prints. gremlins finds the changed lines with git
    // diff --merge-base in the folder it starts in; the fake also has git print the same diff with no
    // config but the mutation step's own. (review drops GIT_EXTERNAL_DIFF and GIT_DIFF_OPTS for
    // everything it starts, the steps included; tests/diffs.rs checks that.)
    fs::write(
        w.home.join(".gitconfig"),
        "[diff]\n\tcontext = 10\n\tnoprefix = true\n\talgorithm = patience\n\tsrcPrefix = SRC/\n[color]\n\tui = always\n\tdiff = always\n[core]\n\tabbrev = 20\n",
    )
    .unwrap();
    let (seen, plain, config) = (
        w.root().join("gremlins.diff"),
        w.root().join("plain.diff"),
        w.root().join("config.diff"),
    );
    let step = "-c diff.relative=true -c diff.context=0 -c color.diff=false";
    let env = gremlins_env(
        &w,
        Some(&[
            format!("git diff --merge-base \"$3\" > '{}'", seen.display()),
            format!(
                "GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_COUNT=0 git -c core.abbrev=12 {step} diff --merge-base \"$3\" > '{}'",
                plain.display()
            ),
            format!(
                "GIT_CONFIG_COUNT=0 git {step} diff --merge-base \"$3\" > '{}'",
                config.display()
            ),
        ]
        .join("\n")),
    );
    mutation(&w, &run, None, &env);
    let plain = fs::read_to_string(&plain).unwrap();
    assert!(plain.contains("\n+\ta := n - 1\n"), "{plain}");
    // Without the step's settings, the user's config would change the diff.
    assert_ne!(fs::read_to_string(&config).unwrap(), plain);
    assert_eq!(fs::read_to_string(&seen).unwrap(), plain);
}
