/// The environment of a step that finds the fakes' gremlins, or none when gremlins is None.
fn gremlins_env(w: &Whooper, gremlins: Option<&str>) -> Vec<(&'static str, String)> {
    let gobin = w.root().join("gobin");
    fs::create_dir_all(&gobin).unwrap();
    let path = match gremlins {
        Some(body) => {
            w.fake("gremlins", body);
            format!("{}:{}", w.fakes.display(), std::env::var("PATH").unwrap())
        }
        None => path_without(&["gremlins"]),
    };
    vec![("PATH", path), ("GOBIN", gobin.display().to_string())]
}

fn mutation(w: &Whooper, run: &Path, seconds: Option<f64>, env: &[(&str, String)]) -> Value {
    let env: Vec<(&str, &str)> = env.iter().map(|(k, v)| (*k, v.as_str())).collect();
    w.step_file("mutation", run, "test_gaps.json", seconds, &env)
        .unwrap()
}

#[test]
fn mutation_keeps_lines_the_diff_adds_one_change_a_line_and_7_lines_a_file_survived_first() {
    let w = Whooper::new();
    // A fake gremlins reports a caught change on each of 9 changed lines, a surviving one on a tenth,
    // one on a line the PR leaves alone, one that ran out of time, and one that did not compile.
    let base = [
        ("go.mod", get(MUT, "go.mod")),
        (
            "calc/sum.go",
            "package calc\n\nfunc Sum(n int) int {\n\treturn n\n}\n",
        ),
        (
            "calc/sum_test.go",
            "package calc\n\nimport \"testing\"\n\nfunc TestSum(t *testing.T) {\n\tSum(1)\n}\n",
        ),
    ];
    let sum = format!(
        "package calc\n\nfunc Sum(n int) int {{\n\ts := n\n{}\treturn s\n}}\n",
        "\ts = s + 1\n".repeat(10)
    );
    let run = w.run_dir(&base, &over(&base, &[("calc/sum.go", &sum)]));
    gaps(&w, &run, None, &[]).unwrap();
    let mutant = |line: i64, status: &str, kind: &str| json!({"type": kind, "status": status, "line": line, "column": 8});
    let mut report: Vec<Value> = (5..14)
        .map(|n| mutant(n, "KILLED", "ARITHMETIC_BASE"))
        .collect();
    report.extend([
        mutant(14, "LIVED", "CONDITIONALS_BOUNDARY"),
        mutant(3, "LIVED", "ARITHMETIC_BASE"),
        mutant(4, "TIMED OUT", "ARITHMETIC_BASE"),
        mutant(15, "NOT VIABLE", "ARITHMETIC_BASE"),
    ]);
    let report_path = w.root().join("report.json");
    fs::write(
        &report_path,
        json!({"files": [{"file_name": "sum.go", "mutations": report}]}).to_string(),
    )
    .unwrap();
    let args = w.root().join("args");
    let env = gremlins_env(
        &w,
        Some(&[
            format!("printf \"%s\\n\" \"$PWD\" \"$GOPROXY $GOTOOLCHAIN $GIT_CONFIG_COUNT $GIT_CONFIG_KEY_0=$GIT_CONFIG_VALUE_0 $GIT_CONFIG_KEY_1=$GIT_CONFIG_VALUE_1 $GIT_CONFIG_KEY_2=$GIT_CONFIG_VALUE_2\" \"$@\" > \"{}\"", args.display()),
            "while [ $# -gt 1 ]; do [ \"$1\" = --output ] && out=\"$2\"; shift; done".into(),
            format!("cp \"{}\" \"$out\"", report_path.display()),
        ]
        .join("\n")),
    );
    let gaps = mutation(&w, &run, None, &env);
    // The surviving change's operator is not one its kind changes, so it shows by its kind.
    let mut lines: Vec<Value> = (5..11)
        .map(|n| json!({"path": "calc/sum.go", "line": n, "status": "caught", "change": "`+` to `-`"}))
        .collect();
    lines.push(
        json!({"path": "calc/sum.go", "line": 14, "status": "survived",
                      "change": "gremlins's CONDITIONALS_BOUNDARY change at column 8"}),
    );
    assert_eq!(gaps["lines"], json!(lines));
    assert_eq!(
        gaps["summary"],
        json!({"changed_lines": 12, "run": 12, "not_run": 0, "survived": 1, "caught": 6})
    );
    assert_eq!(
        gaps["limits"].as_array().unwrap().last().unwrap(),
        "Whooper shows at most 7 survived or caught lines a file, survived first, so it left out 3 lines of calc/sum.go."
    );
    let recorded = fs::read_to_string(&args).unwrap();
    let lines: Vec<&str> = recorded.lines().collect();
    let merge_base = read_json(&run.join("run.json"))["merge_base"]
        .as_str()
        .unwrap()
        .to_string();
    assert_eq!(
        (fs::canonicalize(lines[0]).unwrap(), lines[1]),
        (
            fs::canonicalize(&run).unwrap().join("head/calc"),
            "off local 20 diff.relative=true diff.context=0 color.diff=false"
        )
    );
    let rest = &lines[2..];
    assert_eq!(rest[..3], ["unleash", "--diff", merge_base.as_str()]);
    assert_eq!(rest[5..], ["--workers", "2", "--timeout-coefficient", "10"]);
}

