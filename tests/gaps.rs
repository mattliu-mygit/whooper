/// GAPS' calc_test.go with allowed, lines of Go, as the end of TestAllowed.
fn gaps_tests(allowed: &str) -> String {
    get(GAPS, "calc/calc_test.go").replace(
        "\tAllowed(false, 5)\n}",
        &format!("\tAllowed(false, 5)\n{allowed}\n}}"),
    )
}

fn gaps(w: &Whooper, run: &Path, seconds: Option<f64>, env: &[(&str, &str)]) -> Option<Value> {
    w.step_file("test-gaps", run, "test_gaps.json", seconds, env)
}

fn pick(value: &Value, keys: &[&str]) -> Value {
    Value::Object(
        keys.iter()
            .map(|k| (k.to_string(), value[k].clone()))
            .collect(),
    )
}

fn pid_in(path: &Path) -> i32 {
    fs::read_to_string(path).unwrap().trim().parse().unwrap()
}

/// Go code that writes the test's process ID to pid and then waits a minute.
fn go_waits(pid: &Path) -> String {
    format!(
        "\tos.WriteFile(\"{}\", []byte(strconv.Itoa(os.Getpid())), 0o644)\n\ttime.Sleep(time.Minute)",
        pid.display()
    )
}

fn assert_stopped(pid: &Path) {
    let pid = pid_in(pid);
    let ended = ends_within(pid, 5);
    if !ended {
        unsafe { libc::kill(pid, libc::SIGKILL) };
    }
    assert!(ended, "the test still runs");
}

