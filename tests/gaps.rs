#[test]
fn the_go_tests_stop_at_the_steps_time_limit_and_leave_no_test_running() {
    let w = Whooper::new();
    let pid = w.root().join("test.pid");
    let tests = gaps_tests(&go_waits(&pid))
        .replace("\t\"testing\"", "\t\"os\"\n\t\"strconv\"\n\t\"testing\"");
    let run = w.run_dir(GAPS, &over(&gaps_pr(), &[("calc/calc_test.go", &tests)]));
    let started = Instant::now();
    let gaps = gaps(&w, &run, Some(20.0), &[]).unwrap();
    assert!(started.elapsed() < Duration::from_secs(35));
    assert_eq!(
        pick(&gaps, &["measured", "reason", "lines"]),
        json!({"measured": false, "reason": "The tests ran past Whooper's 20-second limit.", "lines": []})
    );
    assert_stopped(&pid);
}

